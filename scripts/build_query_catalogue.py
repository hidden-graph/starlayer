"""scripts/build_query_catalogue.py - validate the code-KG query library and write its readable catalogue.

The library itself, ``tools/kg/codekg/curated/query-library.ttl``, is hand-edited: it is the
source for the named queries (each an ``sqe:`` tree), their topics, parameters and the competency questions. This
script does not generate it. It checks the library (shapes, and every tree against the sqe shapes) and writes
``docs/generated/query-library.generated.md``, a catalogue small enough to read whole.

Build-time only, like the other scripts here. Run: ``python scripts/build_query_catalogue.py [--check]``.
With ``--check`` nothing is written; the exit status is 1 if the library is invalid or the catalogue is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = ROOT / "docs/generated/query-library.generated.md"

_MARKS = {"answerable": "✅", "roadmap": "🔜", "curated": "🗂️", "out-of-scope": "⛔"}


def render_catalogue() -> str:
    from codekg import queries

    lines = [
        "# Code knowledge graph: query library",
        "",
        "<!-- Generated by scripts/build_query_catalogue.py from codekg/curated/query-library.ttl. Do not edit. -->",
        "",
        "Named queries over the code knowledge graph. Run one with `codekg.queries.run_query(name, **params)`, or",
        "`python scripts/kg.py run <name> param=value`. Results are limited to 25 rows by default.",
        "",
    ]
    topic_labels = queries.topics()
    for topic_id, label in sorted(topic_labels.items(), key=lambda item: item[1]):
        members = queries.list_queries(topic=topic_id)
        if not members:
            continue
        lines += [f"## {label}", ""]
        for q in members:
            params = ", ".join(f"`{p.name}`" + ("" if p.required else " (optional)") for p in q.parameters)
            lines.append(f"- **`{q.name}`** ({params or 'no parameters'}): {q.label}. {q.description}")
        lines.append("")

    questions = queries.competency_questions()
    lines += [
        "## Competency questions",
        "",
        "Questions the code knowledge graph should answer, and whether it can yet: "
        + " · ".join(f"{mark} {status}" for status, mark in _MARKS.items())
        + ". A question with a query lists it.",
        "",
    ]
    for topic_id, label in sorted(topic_labels.items(), key=lambda item: item[1]):
        members = [q for q in questions if q.topic == topic_id]
        if not members:
            continue
        lines += [f"### {label}", ""]
        for q in members:
            text = f"- {_MARKS[q.status]} {q.question}"
            if q.note:
                text += f" — {q.note}"
            if q.answered_by:
                text += " (" + ", ".join(f"`{name}`" for name in q.answered_by) + ")"
            lines.append(text)
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 if the library is invalid or the catalogue stale")
    args = parser.parse_args()

    sys.path.insert(0, str(ROOT / "packages/starlayer"))
    sys.path.insert(0, str(ROOT / "tools/kg"))
    from codekg import queries

    problems = queries.validate_library()
    if problems:
        print("invalid query library:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    catalogue = render_catalogue()

    if args.check:
        if not CATALOGUE.exists() or CATALOGUE.read_text(encoding="utf-8") != catalogue:
            print(f"stale: {CATALOGUE.relative_to(ROOT)} - run `python scripts/build_query_catalogue.py`", file=sys.stderr)
            return 1
        print("query library is valid and its catalogue is current")
        return 0

    CATALOGUE.write_text(catalogue, encoding="utf-8")
    print(f"query library is valid; wrote {CATALOGUE.relative_to(ROOT)} ({len(queries.list_queries())} queries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
