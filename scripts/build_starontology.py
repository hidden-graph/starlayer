"""scripts/build_starontology.py - builds the generated parts of
``packages/starlayer/starlayer/starontology/``.

The ``.ttl`` files in its folders are the source, except the four this build generates:

1. ``skos/skos-ontology.ttl`` from the W3C's ``skos/skos.rdf`` (kept beside it),
2. ``shacl/shacl12-shacl.ttl`` (the SHACL 1.2 meta-shapes) from the Working Group's shacl-shacl and this project's
   ``_sources/shacl12-validation-shapes.ttl``,
3. ``shacl/shacl12-vocabulary.ttl`` (the SHACL 1.2 vocabulary, from the vendored W3C files),
4. ``shacl/shacl12-shacl-ui.ttl`` (the UI companion: the hand-edited overlay plus the form shapes generated from it,
   ``build_shacl_ui.py``); fails if shacl_shacl validates a predicate no form has a field for.

A file is rewritten only when its graph actually changed (compared by graph
isomorphism, not bytes: blank node labels are not stable across serializations), so
a rerun on an unchanged tree changes nothing.

Not part of normal application use: nothing in the library runs this. Run it after editing the sources in ``_sources/`` (the validation shapes, the overlays, the vendored W3C files).

Run:
    python scripts/build_starontology.py            # build
    python scripts/build_starontology.py --check    # change nothing; exit 1 if anything is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_PACKAGES_STARLAYER = Path(__file__).resolve().parents[1] / "packages" / "starlayer"
if str(_PACKAGES_STARLAYER) not in sys.path:
    sys.path.insert(0, str(_PACKAGES_STARLAYER))

from starlayer import starontology  # noqa: E402
from starlayer.graph import StarLayerGraph as Graph  # noqa: E402
from starlayer.graph import isomorphic  # noqa: E402

_DIR = _PACKAGES_STARLAYER / "starlayer" / "starontology"
_SOURCES = _DIR / "_sources"
_SKOS_ORIGINAL = _DIR / "skos" / "skos.rdf"
_SKOS_TTL = _DIR / "skos" / "skos-ontology.ttl"
_SHACL_TTL = _DIR / "shacl" / "shacl12-shacl.ttl"
_UI_TTL = _DIR / "shacl" / "shacl12-shacl-ui.ttl"
_VOCABULARY_TTL = _DIR / "shacl" / "shacl12-vocabulary.ttl"
_VOCABULARY_SOURCE = _SOURCES / "vendor" / "w3c-shacl.ttl"
_VOCABULARY_UI_SOURCE = _SOURCES / "vendor" / "w3c-shacl-ui.ttl"
_VOCABULARY_OVERLAY = _SOURCES / "shacl12-vocabulary-overlay.ttl"

_SKOS_NOTICE = """\
# Copyright (c) 2009 World Wide Web Consortium. https://www.w3.org/copyright/document-license-2023/
# SKOS vocabulary: https://www.w3.org/TR/skos-reference/skos.rdf (original, RDF/XML)
# Part of: SKOS Simple Knowledge Organization System Reference,
#   W3C Recommendation, 18 August 2009, https://www.w3.org/TR/skos-reference/
# This file includes material copied from that document, converted from RDF/XML to
# Turtle with no change to its content.
"""

_SHACL_NOTICE = """\
# GENERATED by scripts/build_starontology.py - do not edit by hand.
# The SHACL 1.2 meta-shapes: pySHACL's bundled shacl-shacl (adjusted for the rules
# SHACL 1.2 widened) plus StarLayer's shacl12-validation-shapes.ttl.
"""


_UI_NOTICE = """\
# GENERATED by scripts/build_starontology.py (scripts/build_shacl_ui.py) - do not edit by hand.
# The UI companion of shacl_shacl: the hand-edited source packages/starlayer/starlayer/starontology/_sources/shacl12-shacl-ui-overlay.ttl (property groups, sh:group
# and sh:order per predicate, form flags) plus the form shapes generated from it (stsh:NodeShapeForm, stsh:PropertyShapeForm).
"""

_VOCABULARY_NOTICE = """\
# GENERATED by scripts/build_starontology.py - do not edit by hand.
# The SHACL 1.2 vocabulary: the W3C Data Shapes WG's shacl.ttl (packages/starlayer/starlayer/starontology/_sources/vendor/w3c-shacl.ttl, see VENDORED_FROM.md there),
# the sh: classes and properties with their rdfs:domain, rdfs:range and rdfs:subClassOf, the WG's shacl-ui.ttl (packages/starlayer/starlayer/starontology/_sources/vendor/
# w3c-shacl-ui.ttl, the shui: classes and properties), plus StarLayer's additions
# (packages/starlayer/starlayer/starontology/_sources/shacl12-vocabulary-overlay.ttl: what a shapes graph holds).
"""


def _filenames() -> list[str]:
    """Every registered .ttl file, in a fixed order."""
    names = {f for f in starontology._FILENAME_BY_NAME.values()}
    names.add(starontology._PROFILES_FILENAME)
    return sorted(names)


def _parse(path: Path) -> Graph:
    graph = Graph()
    graph.parse(str(path), format="turtle")
    return graph


def _turtle_parts(graph: Graph) -> tuple[str, str]:
    """``(extra prefix lines, body)``: the graph as Turtle with the registry's prefixes bound.

    The body has no @prefix lines. A namespace the registry does not know is written as full IRIs, so the body never refers to an undeclared prefix.
    """
    out = Graph()
    for prefix, namespace in starontology._PREFIXES.items():
        out.bind(prefix, namespace)
    for triple in graph:
        out.add(triple)
    lines = out.serialize(format="turtle").splitlines()
    # Only the header: a later line that starts with '@prefix' is inside a multi-line literal and must stay.
    header = 0
    while header < len(lines) and (lines[header].startswith("@prefix") or not lines[header].strip()):
        header += 1
    extra = "".join(f"{line}\n" for line in lines[:header] if line.startswith("@prefix") and line.split()[1][:-1] not in starontology._PREFIXES)
    return extra, "\n".join(lines[header:]).strip()


def _turtle_body(graph: Graph) -> str:
    return _turtle_parts(graph)[1]


def _prefix_lines() -> str:
    return "".join(f"@prefix {p}: <{ns}> .\n" for p, ns in sorted(starontology._PREFIXES.items()))


def _write_ttl(path: Path, notice: str, graph: Graph, *, check: bool) -> bool:
    """Write ``graph`` as ``path`` unless the file already holds an isomorphic graph.
    Returns True if the file is (or, with ``check``, would be) changed."""
    if path.exists() and isomorphic(_parse(path), graph):
        return False
    if not check:
        extra, body = _turtle_parts(graph)
        path.write_text(notice + "\n" + _prefix_lines() + extra + "\n" + body + "\n", encoding="utf-8")
    return True


def build(check: bool) -> int:
    generated = {str(p.relative_to(_DIR)) for p in (_SKOS_TTL, _SHACL_TTL, _VOCABULARY_TTL, _UI_TTL)}  # written by this build, so absent is fine
    missing = [f for f in _filenames() if f not in generated and not (_DIR / f).exists()]
    if missing:
        print(f"ABORT: registered files missing: {missing}", file=sys.stderr)
        return 1
    stale: list[str] = []

    original = Graph().parse(str(_SKOS_ORIGINAL), format="xml")
    if _write_ttl(_SKOS_TTL, _SKOS_NOTICE, original, check=check):
        stale.append(str(_SKOS_TTL.relative_to(_DIR)))

    from build_meta_shapes import build_meta_shapes_graph

    if _write_ttl(_SHACL_TTL, _SHACL_NOTICE, build_meta_shapes_graph(), check=check):
        stale.append(str(_SHACL_TTL.relative_to(_DIR)))

    if _write_ttl(_VOCABULARY_TTL, _VOCABULARY_NOTICE, _parse(_VOCABULARY_SOURCE) + _parse(_VOCABULARY_UI_SOURCE) + _parse(_VOCABULARY_OVERLAY), check=check):
        stale.append(str(_VOCABULARY_TTL.relative_to(_DIR)))

    from build_shacl_ui import (
        build_shacl_ui_graph,
        missing_fields,
        missing_vocabulary_fields,
    )

    ui = build_shacl_ui_graph()
    absent = missing_fields(ui) | missing_vocabulary_fields(ui, _parse(_VOCABULARY_SOURCE) + _parse(_VOCABULARY_UI_SOURCE) + _parse(_VOCABULARY_OVERLAY))
    if absent:
        print("ABORT: shacl_shacl validates predicates no form shape has a field for (add a flag in "
              "_sources/shacl12-shacl-ui-overlay.ttl, or an entry in build_shacl_ui.EXCLUDED with the reason): "
              + ", ".join(sorted(p.value for p in absent)), file=sys.stderr)
        return 1
    if _write_ttl(_UI_TTL, _UI_NOTICE, ui, check=check):
        stale.append(str(_UI_TTL.relative_to(_DIR)))

    if check:
        print("stale: " + ", ".join(stale) if stale else "up to date")
        return 1 if stale else 0
    print("rebuilt: " + ", ".join(stale) if stale else "nothing to rebuild")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 if anything is stale")
    raise SystemExit(build(parser.parse_args().check))
