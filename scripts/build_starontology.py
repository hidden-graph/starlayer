"""scripts/build_starontology.py - builds the generated parts of
``packages/starlayer/starlayer/starontology/``.

The ``.ttl`` files in that directory are the source. This build:

1. regenerates ``skos-ontology.ttl`` from the W3C's ``skos.rdf`` (kept beside it),
2. regenerates ``shacl12-shacl.ttl`` (the SHACL 1.2 meta-shapes) from pySHACL's
   own shacl-shacl and this project's ``shacl12-validation-shapes.ttl``,
3. assembles ``starontology.trig``, every registered ``.ttl`` as a named graph in
   one file, for tooling that wants them all at once, and
4. checks that each named graph in the trig is isomorphic to its ``.ttl`` file.

A file is rewritten only when its graph actually changed (compared by graph
isomorphism, not bytes: rdflib's Turtle output labels blank nodes randomly), so
a rerun on an unchanged tree changes nothing.

Not part of normal application use: nothing in the library runs this or reads
the trig. Run it after editing the validation shapes, upgrading pySHACL, or
editing any ``.ttl`` there.

Run:
    python scripts/build_starontology.py            # build
    python scripts/build_starontology.py --check    # change nothing; exit 1 if anything is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_PACKAGES_STARLAYER = Path(__file__).resolve().parents[1] / "packages" / "starlayer"
if str(_PACKAGES_STARLAYER) not in sys.path:
    sys.path.insert(0, str(_PACKAGES_STARLAYER))

from rdflib import Dataset, Graph, URIRef  # noqa: E402
from rdflib.compare import isomorphic  # noqa: E402

from starlayer import starontology  # noqa: E402

_DIR = _PACKAGES_STARLAYER / "starlayer" / "starontology"
_TRIG = _DIR / "starontology.trig"
_SKOS_ORIGINAL = _DIR / "skos.rdf"
_SKOS_TTL = _DIR / "skos-ontology.ttl"
_SHACL_TTL = _DIR / "shacl12-shacl.ttl"

_SKOS_NOTICE = """\
# Copyright (c) 2009 World Wide Web Consortium. https://www.w3.org/copyright/document-license-2023/
# SKOS vocabulary: https://www.w3.org/TR/skos-reference/skos.rdf (original, RDF/XML)
# Part of: SKOS Simple Knowledge Organization System Reference,
#   W3C Recommendation, 18 August 2009, https://www.w3.org/TR/skos-reference/
# This file includes material copied from that document, converted from RDF/XML to
# Turtle with no change to its content.
"""

_SHACL_NOTICE = """\
# GENERATED by scripts/build_starontology.py - do not edit by hand.
# The SHACL 1.2 meta-shapes: pySHACL's bundled shacl-shacl (adjusted for the rules
# SHACL 1.2 widened) plus StarLayer's shacl12-validation-shapes.ttl.
"""


def _filenames() -> list[str]:
    """Every registered .ttl file, in a fixed order."""
    names = {f for f in starontology._FILENAME_BY_NAME.values()}
    names.add(starontology._PROFILES_FILENAME)
    return sorted(names)


def _parse(path: Path) -> Graph:
    graph = Graph()
    graph.parse(str(path), format="turtle")
    return graph


def _turtle_body(graph: Graph) -> str:
    """The graph as Turtle with the registry's prefixes bound and no @prefix lines."""
    out = Graph()
    for prefix, namespace in starontology._PREFIXES.items():
        out.bind(prefix, namespace, replace=True)
    for triple in graph:
        out.add(triple)
    text = out.serialize(format="turtle")
    return "\n".join(line for line in text.splitlines() if not line.startswith("@prefix")).strip()


def _prefix_lines() -> str:
    return "".join(f"@prefix {p}: <{ns}> .\n" for p, ns in sorted(starontology._PREFIXES.items()))


def _write_ttl(path: Path, notice: str, graph: Graph, *, check: bool) -> bool:
    """Write ``graph`` as ``path`` unless the file already holds an isomorphic graph.
    Returns True if the file is (or, with ``check``, would be) changed."""
    if path.exists() and isomorphic(_parse(path), graph):
        return False
    if not check:
        path.write_text(notice + "\n" + _prefix_lines() + "\n" + _turtle_body(graph) + "\n", encoding="utf-8")
    return True


def _leading_comment(path: Path) -> list[str]:
    lines = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("#"):
            break
        lines.append(line)
    return lines


def _indent(text: str) -> str:
    """Indent Turtle by four spaces, leaving the inside of multi-line
    triple-quoted literals alone (indenting those would change the data)."""
    out, inside = [], False
    for line in text.split("\n"):
        out.append(line if inside or not line else "    " + line)
        if line.count('"""') % 2 == 1:
            inside = not inside
    return "\n".join(out)


def _assemble_trig() -> str:
    blocks = []
    for filename in _filenames():
        path = _DIR / filename
        graph = _parse(path)
        comment = "".join("    " + line + "\n" for line in _leading_comment(path))
        comment += "\n" if comment else ""
        blocks.append(f"starontology:{filename} {{\n{comment}{_indent(_turtle_body(graph))}\n}}\n")
    return _prefix_lines() + "\n" + "\n".join(blocks)


def _trig_graphs(text: str) -> dict[str, Graph]:
    ds = Dataset()
    ds.parse(data=text, format="trig")
    base = starontology._GITHUB_BLOB_BASE
    result = {}
    for g in ds.graphs():
        if len(g):
            graph = Graph()
            for triple in g:
                graph.add(triple)
            result[str(g.identifier)[len(base) :]] = graph
    return result


def build(check: bool) -> int:
    stale: list[str] = []

    original = Graph().parse(str(_SKOS_ORIGINAL), format="xml")
    if _write_ttl(_SKOS_TTL, _SKOS_NOTICE, original, check=check):
        stale.append(_SKOS_TTL.name)

    from starlayer.shacl.meta_shapes import build_meta_shapes_graph

    if _write_ttl(_SHACL_TTL, _SHACL_NOTICE, build_meta_shapes_graph(), check=check):
        stale.append(_SHACL_TTL.name)

    expected = {f: _parse(_DIR / f) for f in _filenames()}
    current = _trig_graphs(_TRIG.read_text(encoding="utf-8")) if _TRIG.exists() else {}
    trig_stale = current.keys() != expected.keys() or any(not isomorphic(current[k], expected[k]) for k in expected)
    if trig_stale:
        stale.append(_TRIG.name)
        if not check:
            text = _assemble_trig()
            rebuilt = _trig_graphs(text)
            if rebuilt.keys() != expected.keys() or any(not isomorphic(rebuilt[k], expected[k]) for k in expected):
                print("ABORT: assembled trig is not isomorphic to the .ttl files", file=sys.stderr)
                return 1
            _TRIG.write_text(text, encoding="utf-8")

    missing = [f for f in _filenames() if not (_DIR / f).exists()]
    if missing:
        print(f"ABORT: registered files missing: {missing}", file=sys.stderr)
        return 1
    if check:
        print("stale: " + ", ".join(stale) if stale else "up to date")
        return 1 if stale else 0
    print("rebuilt: " + ", ".join(stale) if stale else "nothing to rebuild")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 if anything is stale")
    raise SystemExit(build(parser.parse_args().check))
