"""SHACL shapes over the ``salg:`` vocabulary — structural validation for an
algebra graph (LLM-authored or hand-authored) *before* attempting
``from_rdf.rdf_to_query``/``rdf_to_update``.

Scope: core graph-pattern operators (``BGP``/``Filter``/``LeftJoin``/
``Union``/``Extend``/``Minus``/``ServiceGraphPattern``/``Join``/
``ToMultiSet``), the ``TriplePattern``/``TripleTerm``/``Variable``
conventions, all five property path types, ``VALUES``, aggregates/
``GROUP BY`` (all 7 real ``Aggregate_*`` forms), ``Slice``/``Distinct``/
``Reduced``/``OrderBy``, every query form (``SELECT``/``CONSTRUCT``/``ASK``/
``DESCRIBE``), full SPARQL Update (all ten operations), and
``salg:QueryCollection``. Any new operator needs its own shape added the
same way — see ``salg:GraphPatternShape``'s ``sh:or`` list in
``sparql_shapes.ttl`` (loaded below as ``SHAPES_TURTLE``), which is the one
place a new operator's shape must be registered for it to be accepted
inside a nested ``p``/``p1``/``p2`` position. If this note and the shape
inventory below ever disagree, trust the code: grep for
``^salg:[A-Za-z_]*Shape$`` to get the real, current list.

Full expression-tree validation (``Filter``/``LeftJoin``/``Extend``/
``OrderCondition``'s ``expr``) is now done — all 63 of rdflib's expression
builtins (see ``from_rdf._discover_expr_evalfns``) have their own shape,
grouped into reusable argument-signature families; see
``salg:ExpressionShape`` and ``_EXPR_NODE_FAMILY`` below. One deliberate
exception: ``Builtin_EXISTS``/``Builtin_NOTEXISTS``'s ``.graph`` property
is a *raw, untranslated* SPARQL parse-tree fragment (rdflib evaluates
``EXISTS``/``NOT EXISTS`` lazily, translating it on demand at evaluation
time rather than at parse time) — a genuinely different vocabulary from
the translated-algebra shapes everything else here targets. Validating
that separate vocabulary is out of scope for this pass, so ``.graph`` is
checked for cardinality only, same as the still-open gaps above.

**Known limitation, shared with ``GraphPatternShape``: this file uses
``sh:class`` (a plain type-membership check), never ``sh:node``, inside
any dispatch ``sh:or`` list (``GraphPatternShape``, ``ExpressionShape``)
— never the reverse.** ``sh:node`` triggers full recursive shape
conformance and pushes onto pyshacl's own shape-evaluation stack;
``pyshacl``'s shape-recursion guard (``constraints/
constraint_component.py::recursion_triggers``) tracks *shape identity*
in that stack, not (shape, focus-node) pairs, so it cannot distinguish a
true data cycle from a merely-deep-but-finite tree — it can misfire on
very shallow, everyday queries (not just pathologically deep ones) when a
dispatch shape's own alternatives loop back to it via ``sh:node``.
``sh:class`` never touches that stack, so this is safe regardless of
query depth — see ``GraphPatternShape``'s own comment in
``sparql_shapes.ttl`` for the full account.

Unlike ``to_rdf.py``/``from_rdf.py``, these shapes are hand-authored, not
generated by introspecting rdflib — rdflib has no static schema of "which
keys does a BGP CompValue have" to introspect (they're just assembled ad
hoc inside ``algebra.py``'s translate functions), so there's no live
source of truth to mirror mechanically the way ``_discover_expr_evalfns``
mirrors the parser grammar.

**Known limitation: shape-graph recursion.** ``GraphPatternShape`` (the
"what's valid inside a nested ``p``/``p1``/``p2`` position" shape) refers
to itself indirectly through ``FilterShape``/``LeftJoinShape``/
``UnionShape`` — genuine recursion, since SPARQL patterns nest to
arbitrary depth. SHACL Core does not require conforming processors to
support recursive shapes at all (see
https://www.w3.org/TR/shacl/#shapes-recursion), and pyshacl's concrete
behavior is: after ~3 revisits of the *same* shape in a row it silently
stops validating that branch and treats it as conformant (a
``ShapeRecursionWarning``, not an error) rather than raising. In practice
this means a query nesting the same operator (e.g. ``OPTIONAL`` inside
``OPTIONAL`` inside ``OPTIONAL``...) more than ~3 levels deep will not have
its deepest levels structurally checked — a false-negative risk, not a
false-positive one (it can miss a malformed deep node, it won't reject a
well-formed one). ``rdf:List`` traversal (``BGP.triples``) is *not*
subject to this, since ``TriplePatternListShape`` below is a single
SPARQL-based constraint rather than a recursively-self-referential
NodeShape, specifically to avoid this. Revisit if deep operator nesting
turns out to matter in practice - e.g. by moving the operator-alternation
check to a SPARQL-based constraint the same way the list shape was.
"""

from __future__ import annotations

import warnings

from rdflib import Graph

from starlayer import starontology

from .expr_families import _EXPR_NODE_FAMILY
from .sparql_ontology import ontology_graph

try:
    from pyshacl.errors import ShapeRecursionWarning
except ImportError as exc:  # pragma: no cover - exercised only when pyshacl isn't installed
    raise ImportError(
        "starlayer.sparql.salg.sparql_shapes requires pyshacl - install with "
        "`pip install -e '.[test]'` or `pip install pyshacl`"
    ) from exc

# The hand-authored shapes below used to be a giant inline Python string
# (SHAPES_TURTLE = """...""", ~1700 lines) - moved to a standalone
# sparql_shapes.ttl file 2026-08-16 (now living in the sibling starontology
# package, alongside manch:/skos:'s own ontology/shapes files), mirroring
# salg-ontology.ttl's own already-established pattern (a real, directly-usable
# Turtle file, not a Python string), so it's directly usable by any RDF tool
# without going through this module. Every embedded sh:select query body's
# own """...""" delimiters no longer need Python-level backslash-escaping
# now that they are not nested inside a Python triple-quoted string.
#
# Read via get_ontology_graph().serialize(format='turtle12') (a canonical
# Turtle 1.2 re-serialization of the parsed graph), not a direct file path
# - starontology's own *_TTL_PATH constants are private as of 2026-10-02,
# this is the public way to reach the content now (get_ontology_turtle12()
# was a thin wrapper doing exactly this one-line composition; removed
# 2026-10-03 for being nothing more than that). Safe here specifically
# because this text is immediately concatenated with more Turtle and
# re-parsed below (line ~135) - cosmetic reformatting from the round trip
# through StarLayerGraph cannot change the triples, only how they're written.
SHAPES_TURTLE = starontology.get_ontology_graph("sparql_shacl").serialize(format="turtle12")


def _generate_expression_shapes_turtle() -> str:
    """Generate the 63 short per-expression-node-name declarations, each
    pointing at its family's reusable body shape via ``sh:node``.

    Generated from ``_EXPR_NODE_FAMILY`` rather than hand-written - see
    that table's own docstring for why. Targets ``spexpr:``, not ``salg:``
    - both the target class and the body shape it points at live in the
    shared expression vocabulary (see ``vocab.py``'s own ``SPEXPR``
    definition), not in ``salg:`` itself; a node actually typed
    ``spexpr:{name}`` at runtime would never match a
    ``sh:targetClass salg:{name}`` shape. Carries its own
    ``@prefix spexpr:`` line - self-contained regardless of whether
    whatever this gets concatenated with (``shapes_graph()`` below)
    happens to declare that prefix itself.

    Returns:
        The generated Turtle declarations, newline-terminated, with their
        own leading ``@prefix spexpr:`` line.
    """
    declarations = [
        f"spexpr:{name}Shape a sh:NodeShape ; sh:targetClass spexpr:{name} ; "
        f"sh:node spexpr:_{family}ExprBodyShape ."
        for name, family in _EXPR_NODE_FAMILY.items()
    ]
    return (
        "@prefix spexpr: <https://github.com/hidden-graph/starlayer/ns/sparql/expr#> .\n"
        + "\n".join(declarations)
        + "\n"
    )


def shapes_graph() -> Graph:
    """Build a fresh ``rdflib.Graph`` of the shapes above, merged with
    ``spexpr_shacl``.

    SHACL graphs are mutated by pyshacl during validation, so callers get
    their own copy rather than a shared module-level instance. The
    ``spexpr_shacl`` merge is required, not cosmetic: ``ExpressionShape``/
    ``VariableShape``/``PathShape`` and their own supporting shapes
    (per-builtin body shapes, list helpers) live in their own shared shapes
    graph (see ``vocab.py``'s ``SPEXPR`` definition), not in
    ``sparql_shapes.ttl`` - without this merge, every ``sh:node
    salg:ExpressionShape``-style reference this file's own shapes make
    would point at nothing at all.

    Returns:
        A fresh ``rdflib.Graph`` combining the hand-authored shapes, the
        generated per-builtin expression shapes, and ``spexpr_shacl``.
    """
    turtle = SHAPES_TURTLE + "\n" + _generate_expression_shapes_turtle()
    g = Graph()
    g.parse(data=turtle, format="turtle")
    g += starontology.get_ontology_graph("spexpr_shacl")
    return g


def validate_query(data_graph: Graph) -> tuple[bool, Graph, str]:
    """Validate data_graph against the shapes above.

    Runs with RDFS reasoning enabled (``ont_graph=ontology_graph()``,
    ``inference=ENTAILMENT.RDFS``) - this is what lets ``GraphPatternShape``/
    ``ExpressionShape``/``SubSelectShape`` be a single ``sh:class`` check
    against an abstract superclass (``salg:GraphPattern``/``salg:Expression``/
    ``salg:SubSelect``) instead of enumerating every concrete
    operator/builtin by name: with reasoning on, a node asserted as e.g.
    ``salg:Builtin_STR`` is *also* entailed to be ``rdf:type``
    ``salg:OneArgExpression`` and ``salg:Expression`` (the ontology's own
    ``rdfs:subClassOf`` chain), so ``sh:class salg:Expression`` alone
    matches it. Every individual operator/builtin shape (``BGPShape``,
    ``Builtin_STRShape``, ...) is unaffected either way - RDFS subclass
    reasoning only ever *adds* broader inferred types to an
    already-narrowly-typed node, never invents narrower ones, so
    ``sh:targetClass salg:Builtin_STR`` still fires only for nodes actually
    asserted as that type.

    Goes through ``starlayer.shacl.validate()``, never bare ``pyshacl`` - this
    validates a caller-supplied ``data_graph`` that may be genuine RDF 1.2
    content (a ``salg:`` graph can represent real ``TRIPLE()``/``<<( )>>``
    query syntax), which only ``starlayer.shacl`` understands correctly - the same
    rule ``StarLayerGraph.derive_shape()`` follows.

    Args:
        data_graph: The ``salg:``-encoded algebra graph to validate (e.g.
            from ``to_rdf.query_to_rdf``, or an LLM-authored ``salg:``
            graph not yet decoded).

    Returns:
        A ``(conforms, results_graph, results_text)`` tuple - kept as a
        plain tuple rather than returning ``starlayer.shacl``'s own
        ``ValidationResult`` directly, for backward compatibility with
        every existing caller of this function.
    """
    import starlayer.shacl  # lazy: avoids a circular-import deadlock at module load time
    from starlayer.graph.graph.entailment_regimes import ENTAILMENT
    from starlayer.sparql.salg.native_components import register_salg_native_components

    # salg:noUnboundProjectedVariables (the cross-referential check
    # salg:ProjectShape activates) - registered separately from
    # starlayer.shacl.validate()'s own register_native_components() call below,
    # since it's salg:-specific and starlayer.shacl has no knowledge of that
    # vocabulary. See native_components.py's own module docstring.
    register_salg_native_components()

    # No shape in this file's dispatch shapes (GraphPatternShape/
    # ExpressionShape/SubSelectShape) references another shape by name
    # anymore (sh:class, not sh:node/sh:or-of-shapes - see each one's own
    # comment in SHAPES_TURTLE), so pyshacl's shape-recursion guard
    # shouldn't have anything left to trip on. Kept as a defensive
    # suppression, not because it's expected to fire.
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", category=ShapeRecursionWarning)
        result = starlayer.shacl.validate(
            data_graph,
            shacl_graph=shapes_graph(),
            ont_graph=ontology_graph(),
            inference=ENTAILMENT.RDFS,
            advanced=True,
            max_validation_depth=100,
            # meta_shacl defaults to True in starlayer.shacl.validate() -
            # must be disabled here explicitly. shapes_graph() merges in
            # starontology's own spexpr_shacl graph, which genuinely
            # contains its own sh:select literals (ExpressionShape's
            # supporting shapes) - meta_shacl's own preflight now includes
            # a real SALG structural check for every sh:select/ask/
            # construct it finds (check_sparql_query_text(), see
            # starlayer.shacl/meta_shapes.py), which calls back into this
            # very function. Leaving meta_shacl at its default here would
            # recurse infinitely (confirmed live: "maximum recursion depth
            # exceeded") the moment that check was added - this project's
            # own bundled shapes/ontology are already vetted by this
            # module's own test suite, not arbitrary caller content, so
            # there's nothing to gain from re-running that preflight on
            # every single validate_query() call anyway.
            meta_shacl=False,
        )
    return result.conforms, result.report_graph, result.report_text
