"""Forms for every kind of element a shapes graph holds, and the placement of fields across forms (GitHub issues #89, #91, #92, #105, #67).

The form shapes are generated by ``scripts/build_shacl_ui.py`` from ``scripts/assets/shacl12-shacl-ui-overlay.ttl``; the stored
``shacl12-shacl-ui.ttl`` is what these tests read (``test_shacl_ui_forms.py`` checks it equals a fresh build).
"""

import pytest
from build_shacl_ui import STSH, missing_vocabulary_fields, vocabulary_shape_predicates
from rdflib import RDF, RDFS, Graph, Literal, Namespace, URIRef
from starlayer import starontology
from starlayer.shacl.meta_shapes import meta_validate
from starlayer.shacl.ui_widget_selection import select_widgets

SH = Namespace("http://www.w3.org/ns/shacl#")
SHUI = Namespace("http://www.w3.org/ns/shacl-ui#")
OWL = Namespace("http://www.w3.org/2002/07/owl#")
PREFIXES = (
    "@prefix ex: <http://example.org/> . @prefix sh: <http://www.w3.org/ns/shacl#> . @prefix xsd: <http://www.w3.org/2001/XMLSchema#> . "
    "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> . @prefix owl: <http://www.w3.org/2002/07/owl#> . "
    "@prefix shui: <http://www.w3.org/ns/shacl-ui#> . "
)

# The kind of element each form is for (stsh:formFor), per GitHub issue #105
FORMS = {
    "NodeShapeForm": SH.NodeShape,
    "PropertyShapeForm": SH.PropertyShape,
    "PropertyGroupForm": SH.PropertyGroup,
    "ShapesGraphForm": SH.ShapesGraph,
    "PrefixDeclarationForm": SH.PrefixDeclaration,
    "SPARQLConstraintForm": SH.SPARQLConstraint,
    "SPARQLRuleForm": SH.SPARQLRule,
    "TripleRuleForm": SH.TripleRule,
    "ConstraintComponentForm": SH.ConstraintComponent,
    "ParameterForm": SH.Parameter,
    "AskValidatorForm": SH.SPARQLAskValidator,
    "SelectValidatorForm": SH.SPARQLSelectValidator,
    "FunctionForm": SH.Function,
    "SPARQLFunctionForm": SH.SPARQLFunction,
    "SPARQLTargetForm": SH.SPARQLTarget,
    "WidgetScoreForm": SHUI.WidgetScore,
    "ResultAnnotationForm": SH.ResultAnnotation,
    "RuleSetForm": SH.RuleSet,
    "WidgetForm": SHUI.Widget,
    "WidgetAcceptMatcherForm": SHUI.WidgetAcceptMatcher,
    "ConfigurationForm": SHUI.Configuration,
    "GraphForm": SH.Graph,
    "NamedParameterExpressionFunctionForm": SH.NamedParameterExpressionFunction,
    "ListParameterExpressionFunctionForm": SH.ListParameterExpressionFunction,
}


@pytest.fixture(scope="module")
def ui() -> Graph:
    return starontology.get_ontology_graph("shacl_shacl_ui")


def fields(ui: Graph, name: str) -> dict[URIRef, URIRef]:
    return {next(ui.objects(prop, SH.path)): prop for prop in ui.objects(STSH[name], SH.property)}


def one(ui: Graph, subject, predicate):
    values = list(ui.objects(subject, predicate))
    assert len(values) == 1, (subject, predicate, values)
    return values[0]


def parse(text: str) -> Graph:
    return Graph().parse(data=PREFIXES + text, format="turtle")


def accepted(text: str) -> bool:
    from pyshacl.errors import ReportableRuntimeError

    try:
        return bool(meta_validate(parse(text))[0])
    except ReportableRuntimeError:
        return False


# --------------------------------------------------------------------------- #105: a form for every kind, each with rdf:type


@pytest.mark.parametrize("name,kind", sorted(FORMS.items()))
def test_every_kind_of_element_has_a_form_whose_first_field_is_rdf_type(ui, name, kind) -> None:
    assert (STSH[name], STSH.formFor, kind) in ui and (STSH[name], RDF.type, SH.NodeShape) in ui
    rdf_type = fields(ui, name)[RDF.type]
    assert one(ui, rdf_type, SH.group) == STSH.TypeGroup and (rdf_type, SH.nodeKind, SH.IRI) in ui
    assert not list(ui.objects(rdf_type, SH.maxCount)), "an element may have several types"
    assert one(ui, STSH.TypeGroup, SH.order) == Literal(0), "the type comes first"
    assert one(ui, rdf_type, SH.order) == Literal(1)


def test_a_form_is_found_by_its_class_and_applied_to_nothing(ui) -> None:
    by_class = {o for _s, o in ui.subject_objects(STSH.formFor)}
    assert by_class == set(FORMS.values()), "one form per kind, nothing else has formFor"
    for form in ui.subjects(STSH.formFor, None):
        for target in (SH.targetClass, SH.targetNode, SH.targetSubjectsOf, SH.targetObjectsOf):
            assert (form, target, None) not in ui, "a form is applied to nothing, so loading it never changes what validates"


def test_a_required_field_has_min_count_one_and_an_optional_one_has_none(ui) -> None:
    assert (fields(ui, "SPARQLConstraintForm")[SH.select], SH.minCount, Literal(1)) in ui
    assert (fields(ui, "PrefixDeclarationForm")[SH.prefix], SH.minCount, Literal(1)) in ui
    assert (fields(ui, "PrefixDeclarationForm")[SH.namespace], SH.minCount, Literal(1)) in ui
    assert (fields(ui, "SPARQLRuleForm")[SH.construct], SH.minCount, Literal(1)) in ui
    assert (fields(ui, "WidgetScoreForm")[SHUI.widget], SH.minCount, Literal(1)) in ui
    # sh:select is required of a constraint and a validator but not of a SPARQL function, which may use sh:ask instead
    assert not list(ui.objects(fields(ui, "SPARQLFunctionForm")[SH.select], SH.minCount))
    # a triple rule's subject, predicate and object are all optional: an absent one is the focus node (Inference Rules 11.2)
    for predicate in (SH.subject, SH.predicate, SH.object):
        assert not list(ui.objects(fields(ui, "TripleRuleForm")[predicate], SH.minCount)), predicate
        assert (fields(ui, "TripleRuleForm")[predicate], SH.maxCount, Literal(1)) in ui


def test_the_kind_specific_definition_fields_are_there(ui) -> None:
    assert {SH.parameter, SH.validator, SH.nodeValidator, SH.propertyValidator} <= set(fields(ui, "ConstraintComponentForm"))
    assert {SH.path, SH.optional, SH.keyParameter, SH.name, SH.order, SH.datatype} <= set(fields(ui, "ParameterForm"))
    assert {SH.returnType, SH.parameter} <= set(fields(ui, "FunctionForm"))
    assert {SH.layer, SH.runOnce, SH.expectedPredicate, SH.condition} <= set(fields(ui, "TripleRuleForm"))
    assert {SHUI.widget, SHUI.score, SHUI.shapesGraphShape, SHUI.dataGraphShape} == set(fields(ui, "WidgetScoreForm")) - {RDF.type, RDFS.label, RDFS.comment}
    assert {SH.prefixes, SH.select} <= set(fields(ui, "SPARQLTargetForm"))
    assert {RDFS.member, OWL.imports, SH.entailment, SH.declare} <= set(fields(ui, "ShapesGraphForm"))


def test_the_group_and_shapes_graph_forms_have_a_type_a_comment_and_what_defines_them(ui) -> None:
    """GitHub issue #91's second update: a group is defined by a shapes graph too, and both forms miss rdfs:comment and rdf:type."""
    for name in ("PropertyGroupForm", "ShapesGraphForm"):
        assert {RDF.type, RDFS.comment, RDFS.isDefinedBy, RDFS.label} <= set(fields(ui, name)), name
        assert (fields(ui, name)[RDFS.isDefinedBy], SH.maxCount, Literal(1)) in ui


def test_the_group_and_shapes_graph_forms_state_what_a_field_takes(ui) -> None:
    """A tool cannot tell a plain field from a branch of the tree when a field leaves sh:nodeKind open (GitHub issue #91)."""
    group = fields(ui, "PropertyGroupForm")
    for predicate in (SH.name, SH.description, RDFS.label, SH.order, RDFS.comment):
        assert (group[predicate], SH.nodeKind, SH.Literal) in ui, predicate
    assert (fields(ui, "ShapesGraphForm")[RDFS.label], SH.nodeKind, SH.Literal) in ui
    for name in FORMS:
        for predicate, field in fields(ui, name).items():
            if predicate in (SH.subject, SH.predicate, SH.object, SH.path, SH.equals, SH.disjoint, SH.hasValue, SH["in"], SH.defaultValue):
                continue  # a node expression, a path, or a value of any kind: the form cannot say
            if predicate in (SH["and"], SH["or"], SH.xone, SH.ignoredProperties, SH.languageIn, SH.values, SH.expression,
                             SH.lessThan, SH.lessThanOrEquals, SH.memberShape, SH.closed, SH.bodyExpression, SHUI.languagePreference, SHUI.labelPreference):
                continue
            assert list(ui.objects(field, SH.nodeKind)) or list(ui.objects(field, SH.datatype)), (name, predicate, "states neither a node kind nor a datatype")


