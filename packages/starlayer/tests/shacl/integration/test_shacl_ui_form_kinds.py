@pytest.mark.parametrize("holder", ["ex:SG a sh:ShapesGraph", "<http://example.com/ns#> a owl:Ontology", "ex:Holder a rdfs:Resource", "ex:Bare"])
def test_a_declaration_is_checked_whatever_holds_it_and_whether_or_not_anything_uses_it(holder) -> None:
    """A node with sh:declare that is not the object of an sh:prefixes got no check before (the entry could be written and never seen)."""
    good = f'{holder} ; sh:declare [ sh:prefix "ex" ; sh:namespace "http://example.org/"^^xsd:anyURI ] .'
    no_namespace = f'{holder} ; sh:declare [ sh:prefix "ex" ] .'
    two_prefixes = f'{holder} ; sh:declare [ sh:prefix "ex", "e" ; sh:namespace "http://example.org/" ] .'
    literal = f'{holder} ; sh:declare "ex" .'
    assert accepted(good)
    assert not accepted(no_namespace) and not accepted(two_prefixes) and not accepted(literal)


def test_a_declaration_used_by_sh_prefixes_is_still_checked() -> None:
    assert accepted('ex:S a sh:NodeShape ; sh:sparql [ sh:select "SELECT $this WHERE {}" ; sh:prefixes ex:SG ] . ex:SG a sh:ShapesGraph ; sh:declare [ sh:prefix "ex" ; sh:namespace "http://example.org/" ] .')
    assert not accepted('ex:S a sh:NodeShape ; sh:sparql [ sh:select "SELECT $this WHERE {}" ; sh:prefixes ex:SG ] . ex:SG sh:declare [ sh:namespace "http://example.org/" ] .')


