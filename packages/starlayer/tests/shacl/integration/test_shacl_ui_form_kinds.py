# --------------------------------------------------------------------------- #92: one place for a property, whatever the kind


def test_naming_and_messages_are_a_group_directly_after_targeting(ui) -> None:
    orders = {g: one(ui, g, SH.order) for g in ui.subjects(RDF.type, SH.PropertyGroup)}
    after_targeting = sorted((o, g) for g, o in orders.items() if o > orders[STSH.TargetGroup])
    assert after_targeting[0][1] == STSH.NamingGroup and after_targeting[1][1] == STSH.PathGroup
    for name in ("NodeShapeForm", "PropertyShapeForm"):
        for predicate in (SH.name, SH.description, SH.message, SH.severity, SH.deactivated, RDFS.label, RDFS.comment):
            assert one(ui, fields(ui, name)[predicate], SH.group) == STSH.NamingGroup, (name, predicate)
    assert one(ui, STSH.MetadataGroup, SH.order) > one(ui, STSH.PathGroup, SH.order), "the metadata group is still last"
    for predicate in (SH.order, SH.group, SH.defaultValue, RDFS.isDefinedBy):
        assert one(ui, fields(ui, "PropertyShapeForm")[predicate], SH.group) == STSH.MetadataGroup, predicate


def test_a_name_comes_before_its_description_and_the_messages(ui) -> None:
    order = {p: one(ui, f, SH.order) for p, f in fields(ui, "NodeShapeForm").items() if p in (SH.name, SH.description, SH.message, SH.severity, SH.deactivated)}
    assert order[SH.name] < order[SH.description] < order[SH.message] < order[SH.severity] < order[SH.deactivated]


@pytest.mark.parametrize("name", ["NodeShapeForm", "PropertyShapeForm", "ParameterForm"])
def test_value_type_is_ordered_class_rootclass_datatype_nodekind(ui, name) -> None:
    form = fields(ui, name)
    if SH.rootClass not in form:
        form_order = [one(ui, form[p], SH.order) for p in (SH["class"], SH.datatype, SH.nodeKind)]
        assert form_order == sorted(form_order)
        return
    order = [one(ui, form[p], SH.order) for p in (SH["class"], SH.rootClass, SH.datatype, SH.nodeKind)]
    assert order == sorted(order) and len(set(order)) == 4
    assert {one(ui, form[p], SH.group) for p in (SH["class"], SH.rootClass, SH.datatype, SH.nodeKind)} == {STSH.ValueTypeGroup}


def test_a_predicate_has_one_group_and_one_order_in_every_form(ui) -> None:
    """The point of the scheme: a property is in the same place in every kind (the workbench found 32 places where it was not)."""
    seen: dict[URIRef, set] = {}
    for name in FORMS:
        for predicate, field in fields(ui, name).items():
            seen.setdefault(predicate, set()).add((next(ui.objects(field, SH.group), None), next(ui.objects(field, SH.order), None)))
    assert {p: placements for p, placements in seen.items() if len(placements) > 1} == {}


def test_every_field_of_every_form_has_a_group_and_an_order(ui) -> None:
    for name in FORMS:
        for predicate, field in fields(ui, name).items():
            if predicate == SH.path and name != "PropertyShapeForm" and name != "ParameterForm":
                continue
            assert list(ui.objects(field, SH.group)) and len(list(ui.objects(field, SH.order))) == 1, (name, predicate)


def test_a_parameter_orders_its_fields_as_a_property_shape_does(ui) -> None:
    prop, param = fields(ui, "PropertyShapeForm"), fields(ui, "ParameterForm")
    shared = [p for p in param if p in prop]
    assert len(shared) >= 8
    assert sorted(shared, key=lambda p: (one(ui, one(ui, prop[p], SH.group), SH.order), one(ui, prop[p], SH.order))) == sorted(
        shared, key=lambda p: (one(ui, one(ui, param[p], SH.group), SH.order), one(ui, param[p], SH.order))
    )
    for predicate in (SH.optional, SH.keyParameter):
        assert one(ui, param[predicate], SH.group) == STSH.CardinalityGroup


