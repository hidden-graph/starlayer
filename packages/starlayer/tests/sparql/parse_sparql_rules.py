"""The static semantic rules of SPARQL 1.2 Query that the grammar leaves to prose, as positive/negative cases.

Source of the rules: the notes under the grammar (section 19.7: blank node labels, VALUES arity and variable
uniqueness, AS targets not in scope, BIND scope, aggregate placement and nesting, reifiers only after simple paths,
``*`` with GROUP BY) and section 18.3.1 (variable scope). Each rule has negative cases that must be rejected and positive
cases that must be accepted, so a rejection is for the right reason. ``test_parse_sparql_semantics.py`` runs them,
``test_parse_sparql_oxigraph.py`` compares them with Oxigraph.
"""

from __future__ import annotations

from typing import NamedTuple

P = "PREFIX : <http://e/>\n"


class Rule(NamedTuple):
    rule: str
    text: str
    ok: bool


def _r(rule: str, ok: bool, *texts: str) -> list[Rule]:
    return [Rule(rule, P + t, ok) for t in texts]


