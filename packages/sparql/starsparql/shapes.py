"""SHACL shapes over the ``salg:`` vocabulary — structural validation for an
algebra graph (LLM-authored or hand-authored) *before* attempting
``from_rdf.rdf_to_query``/``rdf_to_update``.

Scope: Phase 1's core graph-pattern operators (``BGP``, ``Filter``,
``LeftJoin``, ``Union``, ``Extend``) plus the ``TriplePattern``/``Variable``
conventions and the ``SELECT`` query wrapper (``Project``/``SelectQuery``),
and — from Phase 2 — ``VALUES`` and subqueries: ``Join``, ``ToMultiSet``,
the ``values``/``Binding`` VALUES-row shapes, and the ``Slice``/``OrderBy``/
``OrderCondition`` subquery-wrapper shapes. Still not covered: property
paths, aggregates/``GROUP BY``, Update, ``MINUS``/``SERVICE``,
``CONSTRUCT``/``ASK``/``DESCRIBE``-specific shapes. Each needs its own
shapes added the same way — see ``salg:GraphPatternShape``'s ``sh:or`` list
in ``SHAPES_TURTLE`` below, which is the one place a new operator's shape
must be registered for it to be accepted inside a nested
``p``/``p1``/``p2`` position.

Full expression-tree validation (``Filter``/``LeftJoin``/``Extend``/
``OrderCondition``'s ``expr``) is now done — all 63 of rdflib's expression
builtins (see ``from_rdf._discover_expr_evalfns``) have their own shape,
grouped into reusable argument-signature families; see
``salg:ExpressionShape`` and ``_EXPR_NODE_FAMILY`` below. One deliberate
exception: ``Builtin_EXISTS``/``Builtin_NOTEXISTS``'s ``.graph`` property
is a *raw, untranslated* SPARQL parse-tree fragment (rdflib evaluates
``EXISTS``/``NOT EXISTS`` lazily, translating it on demand at evaluation
time rather than at parse time) — a genuinely different vocabulary from
the translated-algebra shapes everything else here targets, confirmed by
inspecting real decoded algebra output; validating that separate
vocabulary is out of scope for this pass, so ``.graph`` is checked for
cardinality only, same as the still-open gaps above.

**Known limitation, shared with ``GraphPatternShape``: this file uses
``sh:class`` (a plain type-membership check), never ``sh:node``, inside
any dispatch ``sh:or`` list (``GraphPatternShape``, ``ExpressionShape``)
— never the reverse.** ``sh:node`` triggers full recursive shape
conformance and pushes onto pyshacl's own shape-evaluation stack;
``pyshacl``'s shape-recursion guard (``constraints/
constraint_component.py::recursion_triggers``) tracks *shape identity*
in that stack, not (shape, focus-node) pairs, so it cannot distinguish a
true data cycle from a merely-deep-but-finite tree — and confirmed
empirically to misfire on very shallow, everyday queries (not just
pathologically deep ones) when a dispatch shape's own alternatives loop
back to it via ``sh:node``. ``sh:class`` never touches that stack, so
this is safe regardless of query depth — see ``GraphPatternShape``'s own
comment in ``SHAPES_TURTLE`` for the full account, including how this
was actually discovered (a real, previously-undetected gap: ``Extend``,
``BIND``'s algebra node, was missing from ``GraphPatternShape`` entirely
and nothing caught it, because the old ``sh:node``-based dispatch was
silently giving up before it ever reached that check).

Unlike ``to_rdf.py``/``from_rdf.py``, these shapes are hand-authored, not
generated by introspecting rdflib — rdflib has no static schema of "which
keys does a BGP CompValue have" to introspect (they're just assembled ad
hoc inside ``algebra.py``'s translate functions), so there's no live
source of truth to mirror mechanically the way ``_discover_expr_evalfns``
mirrors the parser grammar.

**Known limitation: shape-graph recursion.** ``GraphPatternShape`` (the
"what's valid inside a nested ``p``/``p1``/``p2`` position" shape) refers
to itself indirectly through ``FilterShape``/``LeftJoinShape``/
``UnionShape`` — genuine recursion, since SPARQL patterns nest to
arbitrary depth. SHACL Core does not require conforming processors to
support recursive shapes at all (see
https://www.w3.org/TR/shacl/#shapes-recursion), and pyshacl's concrete
behavior is: after ~3 revisits of the *same* shape in a row it silently
stops validating that branch and treats it as conformant (a
``ShapeRecursionWarning``, not an error) rather than raising. In practice
this means a query nesting the same operator (e.g. ``OPTIONAL`` inside
``OPTIONAL`` inside ``OPTIONAL``...) more than ~3 levels deep will not have
its deepest levels structurally checked — a false-negative risk, not a
false-positive one (it can miss a malformed deep node, it won't reject a
well-formed one). ``rdf:List`` traversal (``BGP.triples``) is *not*
subject to this, since ``TriplePatternListShape`` below is a single
SPARQL-based constraint rather than a recursively-self-referential
NodeShape, specifically to avoid this. Revisit if deep operator nesting
turns out to matter in practice - e.g. by moving the operator-alternation
check to a SPARQL-based constraint the same way the list shape was.
"""

