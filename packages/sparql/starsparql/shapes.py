def _generate_expression_shapes_turtle() -> str:
    """The 63 short per-expression-node-name declarations, each pointing
    at its family's reusable body shape via ``sh:node`` - generated from
    ``_EXPR_NODE_FAMILY`` rather than hand-written. See that table's own
    docstring for why.
    """
    declarations = [
        f"salg:{name}Shape a sh:NodeShape ; sh:targetClass salg:{name} ; "
        f"sh:node salg:_{family}ExprBodyShape ."
        for name, family in _EXPR_NODE_FAMILY.items()
    ]
    return "\n".join(declarations) + "\n"


def shapes_graph() -> Graph:
    """A fresh ``rdflib.Graph`` of the shapes above (SHACL graphs are
    mutated by pyshacl during validation, so callers get their own copy
    rather than a shared module-level instance)."""
    turtle = SHAPES_TURTLE + "\n" + _generate_expression_shapes_turtle()
    g = Graph()
    g.parse(data=turtle, format="turtle")
    return g


def validate(data_graph: Graph) -> tuple[bool, Graph, str]:
    """Validate ``data_graph`` (e.g. from ``to_rdf.query_to_rdf``, or an
    LLM-authored ``salg:`` graph not yet decoded) against the shapes above.

    Runs with RDFS reasoning enabled (``ont_graph=ontology_graph()``,
    ``inference="rdfs"``) - this is what lets ``GraphPatternShape``/
    ``ExpressionShape``/``SubSelectShape`` be a single ``sh:class`` check
    against an abstract superclass (``salg:GraphPattern``/``salg:Expression``/
    ``salg:SubSelect``) instead of enumerating every concrete
    operator/builtin by name: with reasoning on, a node asserted as e.g.
    ``salg:Builtin_STR`` is *also* entailed to be ``rdf:type``
    ``salg:OneArgExpression`` and ``salg:Expression`` (the ontology's own
    ``rdfs:subClassOf`` chain), so ``sh:class salg:Expression`` alone
    matches it - confirmed empirically, not assumed. Every individual
    operator/builtin shape (``BGPShape``, ``Builtin_STRShape``, ...) is
    unaffected either way - RDFS subclass reasoning only ever *adds*
    broader inferred types to an already-narrowly-typed node, never
    invents narrower ones, so ``sh:targetClass salg:Builtin_STR`` still
    fires only for nodes actually asserted as that type.

    Returns ``(conforms, results_graph, results_text)`` — the same shape
    ``pyshacl.validate`` itself returns, so a caller that wants the raw
    SHACL validation report can use it directly.
    """
    # No shape in this file's dispatch shapes (GraphPatternShape/
    # ExpressionShape/SubSelectShape) references another shape by name
    # anymore (sh:class, not sh:node/sh:or-of-shapes - see each one's own
    # comment in SHAPES_TURTLE), so pyshacl's shape-recursion guard
    # shouldn't have anything left to trip on. Kept as a defensive
    # suppression, not because it's expected to fire.
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", category=ShapeRecursionWarning)
        conforms, results_graph, results_text = _pyshacl_validate(
            data_graph,
            shacl_graph=shapes_graph(),
            ont_graph=ontology_graph(),
            inference="rdfs",
            advanced=True,
            max_validation_depth=100,
        )
    return conforms, results_graph, results_text
